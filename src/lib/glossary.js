const norm = (s) => String(s).toLowerCase().replace(/\s+/g, ' ').trim();

export function explain(label) {
  if (typeof label !== 'string' || !label.trim()) return null;
  const full = norm(label);
  if (G[full]) return G[full];
  const simpler = norm(full.split('·')[0].replace(/\([^)]*\)/g, '').replace(/[:%]+$/, ''));
  return G[simpler] || G[norm(simpler.split(':')[0])] || null;
}
