import { fmtMoney } from './format';

const BRAND = [15, 118, 110];
const periodLabel = (p) => { const [y, m] = p.split('-'); return new Date(y, m - 1).toLocaleDateString('en-GB', { month: 'long', year: 'numeric' }); };

// One payslip as a branded A4 PDF (loaded on demand).
export async function downloadPayslipPdf(slip) {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const w = doc.internal.pageSize.getWidth();
  const e = slip.employee;
  // jsPDF's built-in fonts have no ₦ glyph, so amounts use "NGN".
  const amt = (n) => fmtMoney(n).replace('₦', 'NGN ');

  doc.setFillColor(...BRAND).rect(0, 0, w, 80, 'F');
  doc.setTextColor(255).setFont('helvetica', 'bold').setFontSize(18).text(slip.organisation || 'Solucio Hospital', 40, 36);
  doc.setFont('helvetica', 'normal').setFontSize(11).text(`Payslip · ${periodLabel(slip.period)}`, 40, 58);
  doc.setFontSize(9).text('Private & confidential', w - 40, 58, { align: 'right' });

  doc.setTextColor(40).setFontSize(10);
  const left = [['Name', e.name], ['Staff ID', e.staffId], ['Department', e.department], ['Position', e.position], ['Grade', e.grade || '—']];
  const right = [['Bank', e.bankName || '—'], ['Account', e.accountNumber ? `${e.accountNumber}` : '—'], ['Pension (PFA)', e.pfa || '—'], ['RSA PIN', e.pensionPin || '—'], ['TIN', e.taxId || '—']];
  left.forEach(([k, v], i) => { doc.setTextColor(120).text(k, 40, 110 + i * 16); doc.setTextColor(30).text(String(v || '—'), 120, 110 + i * 16); });
  right.forEach(([k, v], i) => { doc.setTextColor(120).text(k, w / 2 + 10, 110 + i * 16); doc.setTextColor(30).text(String(v), w / 2 + 100, 110 + i * 16); });

  const head = { fillColor: BRAND, textColor: 255, fontStyle: 'bold' };
  autoTable(doc, { startY: 200, margin: { left: 40, right: w / 2 + 5 }, head: [['Earnings', 'Amount']], headStyles: head, styles: { fontSize: 9 },
    body: [...slip.earnings.map((x) => [x.name, amt(x.amount)]), [{ content: 'Gross pay', styles: { fontStyle: 'bold' } }, { content: amt(slip.gross), styles: { fontStyle: 'bold' } }]],
    columnStyles: { 1: { halign: 'right' } } });
  const leftEnd = doc.lastAutoTable.finalY;
  autoTable(doc, { startY: 200, margin: { left: w / 2 + 5, right: 40 }, head: [['Deductions', 'Amount']], headStyles: head, styles: { fontSize: 9 },
    body: [...slip.deductions.map((x) => [x.name, amt(x.amount)]), [{ content: 'Total deductions', styles: { fontStyle: 'bold' } }, { content: amt(slip.totalDeductions), styles: { fontStyle: 'bold' } }]],
    columnStyles: { 1: { halign: 'right' } } });
  const y = Math.max(leftEnd, doc.lastAutoTable.finalY) + 24;

  doc.setFillColor(239, 252, 249).roundedRect(40, y, w - 80, 56, 8, 8, 'F');
  doc.setTextColor(...BRAND).setFont('helvetica', 'bold').setFontSize(12).text('Net pay', 56, y + 34);
  doc.setFontSize(20).text(amt(slip.net), w - 56, y + 36, { align: 'right' });

  autoTable(doc, { startY: y + 76, margin: { left: 40, right: 40 }, head: [['Paid by the hospital on your behalf', 'Amount']], headStyles: { fillColor: [100, 116, 139], textColor: 255 }, styles: { fontSize: 9 },
    body: slip.employerContributions.map((x) => [x.name, amt(x.amount)]), columnStyles: { 1: { halign: 'right' } } });
  if (slip.ytd) {
    autoTable(doc, { startY: doc.lastAutoTable.finalY + 16, margin: { left: 40, right: 40 }, head: [['Year to date', 'Gross', 'PAYE', 'Pension', 'Net']], headStyles: { fillColor: [100, 116, 139], textColor: 255 }, styles: { fontSize: 9 },
      body: [[`${slip.ytd.months} month(s)`, amt(slip.ytd.gross), amt(slip.ytd.paye), amt(slip.ytd.pension), amt(slip.ytd.net)]] });
  }
  if (slip.notes?.length) doc.setFont('helvetica', 'italic').setFontSize(8).setTextColor(110).text(slip.notes.join(' · '), 40, doc.lastAutoTable.finalY + 20);
  doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(140).text('Generated by Solucio HR. Contact HR with any questions about your pay.', 40, doc.internal.pageSize.getHeight() - 24);
  doc.save(`payslip_${slip.period}_${(e.staffId || e.name).replace(/\s+/g, '_')}.pdf`);
}

// Save a CSV schedule from the API (bank / pension / PAYE).
export async function downloadCsv(api, url, filename) {
  const res = await api.get(url, { responseType: 'blob' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(res.data);
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 30000);
}
